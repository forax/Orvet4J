# str.format with replacement fields and the format spec mini-language.
print("Hello {}".format("world"))
print("{} + {} = {}".format(2, 3, 5))
print("{0} then {1} then {0}".format("a", "b"))
print("{{literal braces}} {}".format(1))
print("{:>8}|{:8}|".format("left", "right"))
print("{:^9}|".format("center"))
print("{:*^9}|".format("fill"))
print("{:05d}".format(-42))
print("{:+.3f}".format(3.14159))
print("{:#x} {:#o} {:#b}".format(255, 64, 5))
print("{:,}".format(1234567))
print("{:_d}".format(987654321))
print("{:07,d}".format(1234567))
print("{:.3e}".format(12345.6789))
print("{:.1%}".format(0.25))
print("{:c}".format(65))
print("{:.2}".format("truncate"))
print("{!r} {!s}".format("quoted", "plain"))
print("{0[1]} and {1[name]}".format([10, 20], {"name": "x"}))
print("{:>{}}|".format("nest", 10))
print("{:z} {:z}".format(-0.0, 0.0))
print(format(42, "07,d"))
print(format("a", "^5"))
print(format(1.5))
